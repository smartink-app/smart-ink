import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
let mode = 'demo', userId = 'user-a', updateError = null, updated, demoName;
const files = new Map();
const storage = { getItem: key => files.get(key) ?? null, setItem: (key, value) => files.set(key, value) };
const client = { auth: { getUser: async () => ({ data: { user: { id: userId, user_metadata: { full_name: 'Hosted artist' } } } }), updateUser: async data => { updated = data; return { error: updateError }; } } };
const exports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/accountProfile.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, {
  exports, URL, localStorage: storage, require: name => name.includes('betaAuthService') ? { authMode: () => mode } : name.includes('supabaseClient') ? { getSupabase: () => client } : { updateDemoDisplayName: (email, name) => { demoName = name; } }
});
const session = { email: 'artist@example.test', displayName: 'Artist', userId: 'user-a' };
const profile = { displayName: '  New Artist ', studioName: ' Studio ', website: 'https://example.test', bio: ' Fine line ' };
const key = 'smartink:profile:artist@example.test';
files.set(key, JSON.stringify({ future_setting: true }));
const saved = await exports.saveAccountProfile(session, profile);
assert.equal(saved.displayName, 'New Artist');
assert.equal(demoName, 'New Artist');
assert.equal(JSON.parse(files.get(key)).future_setting, true);
assert.equal((await exports.loadAccountProfile(session)).bio, 'Fine line');
assert.equal((await exports.loadAccountProfile({ ...session, email: 'other@example.test' })).displayName, 'Artist');
for (const website of ['javascript:alert(1)', 'ftp://example.test', 'https://name:secret@example.test', 'not a url']) assert.throws(() => exports.validateProfile({ ...profile, website }));
assert.throws(() => exports.validateProfile({ ...profile, displayName: ' ' }));
files.set(key, 'null');
await assert.rejects(exports.saveAccountProfile(session, profile));
assert.equal(files.get(key), 'null');
files.set(key, '{}'); storage.setItem = () => { throw new Error('Storage full'); };
await assert.rejects(exports.saveAccountProfile(session, profile), /Storage full/);
mode = 'supabase'; userId = 'different-account';
await assert.rejects(exports.saveAccountProfile(session, profile), /sign in again/);
await assert.rejects(exports.updateAccountPassword(session, 'long-test-passphrase'), /sign in again/);
userId = 'user-a';
await exports.saveAccountProfile(session, profile);
assert.equal(updated.data.full_name, 'New Artist');
updateError = new Error('Network unavailable');
await assert.rejects(exports.saveAccountProfile(session, profile), /Network unavailable/);
await assert.rejects(exports.updateAccountPassword(session, 'long-test-passphrase'), /Network unavailable/);
updateError = null;
await assert.rejects(exports.updateAccountPassword(session, 'short'), /12 characters/);
await exports.updateAccountPassword(session, 'long-test-passphrase');
assert.equal(updated.password, 'long-test-passphrase');
mode = 'unconfigured';
await assert.rejects(exports.loadAccountProfile(session), /unavailable/);
await assert.rejects(exports.saveAccountProfile(session, profile), /unavailable/);
console.log('Account profile: persistence, isolation, validation, corruption, storage errors, identity checks and hosted errors passed.');
