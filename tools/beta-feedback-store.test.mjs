import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const files = new Map();
const storage = { getItem: k => files.get(k) ?? null, setItem: (k,v) => files.set(k,v) };
const exports = {};
const code = ts.transpileModule(fs.readFileSync('src/beta-feedback/store.ts','utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
vm.runInNewContext(code, { exports, localStorage: storage });
const report = {id:'session-a:front-page',tester:'demo',createdAt:'2026-10-29',kind:'journey',screen:'Front page',target:'Introduction',message:'First comment',expected:'',goal:'',progress:'Step 1 of 8',version:'test',status:'new',notes:''};
exports.saveJourneyReport(report);
exports.updateReport(report.id,{status:'investigating',notes:'Keep operator decision'});
exports.saveJourneyReport({...report,message:'Revised comment'});
assert.equal(exports.readReports().length,1,'Revisiting a step must not duplicate feedback');
assert.equal(exports.readReports()[0].message,'Revised comment');
assert.equal(exports.readReports()[0].notes,'Keep operator decision');
assert.equal(exports.readReports()[0].status,'investigating');
exports.saveJourneyReport({...report,id:'session-b:front-page'});
assert.equal(exports.readReports().length,2,'Separate reviews remain separate');
const draft = { id:'review-1',tester:'alice',startedAt:'now',updatedAt:'now',index:0,isTest:true,steps:[{id:'front-page',title:'Front page'},{id:'saving',title:'Saving'}],answers:[{text:'Private draft',saved:''},{text:'',saved:'',disposition:'not-tried'}] };
exports.persistReview(draft,'paused');
assert.equal(exports.readReviewDraft('alice').answers[0].text,'Private draft');
assert.equal(exports.readReviewDraft('bob'),undefined,'Draft recovery is scoped to the account');
assert.equal(exports.readReviewSessions()[0].steps[0].hasDraft,true);
assert.equal(JSON.stringify(exports.readReviewSessions()).includes('Private draft'),false,'Session summaries exclude draft text');
assert.equal(exports.readReviewSessions()[0].steps[1].outcome,'not-tried');
assert.throws(()=>exports.persistReview(draft,'completed'),/Submit or clear/);
const submitted = {...draft,answers:[{text:'Submitted',saved:'Submitted',disposition:'commented'},draft.answers[1]]};
exports.persistReview(submitted,'in-progress',{...report,id:'review-1:front-page',sessionId:'review-1',message:'Submitted'});
exports.persistReview(submitted,'completed');
assert.equal(exports.readReviewDraft('alice'),undefined);
assert.equal(exports.readReviewSessions()[0].status,'completed');
assert.equal(exports.readReviewSessions()[0].steps[0].outcome,'commented');
exports.saveCommentDraft('alice',{message:'Free form private',expected:'',goal:'',progress:'',target:'',screen:'Projects'});
assert.equal(exports.readCommentDraft('alice').message,'Free form private');
assert.equal(exports.readCommentDraft('bob'),undefined);
exports.saveReport({...report,id:'free-comment',tester:'alice',kind:'comment'});
assert.equal(exports.readCommentDraft('alice'),undefined,'Submitting clears the private draft atomically');
const key=[...files.keys()][0]; files.set(key,'broken JSON');
assert.throws(()=>exports.saveJourneyReport(report));
assert.equal(files.get(key),'broken JSON','Unreadable records must not be overwritten');
files.set(key,'[]'); storage.setItem=()=>{throw new Error('Quota exceeded');};
assert.throws(()=>exports.saveJourneyReport(report),/Quota exceeded/,'A storage failure must reach the UI');
console.log('Journey feedback: idempotent edits, operator notes preserved, separate sessions, corruption and storage failures passed.');
