import assert from 'node:assert/strict';
import { build } from 'esbuild';
let states=[],cursor=0,sent=[],verified=[];
globalThis.loginHooks={state(v){const i=cursor++;if(!(i in states))states[i]=v;return [states[i],v=>states[i]=v];}};
globalThis.loginSend=async email=>{sent.push(email);return {};};
globalThis.loginVerify=async(email,code)=>{verified.push([email,code]);return {email};};
const result=await build({entryPoints:['src/LoginPage.tsx'],bundle:true,define:{'import.meta.env.DEV':'false'},write:false,format:'esm',platform:'node',jsx:'automatic',plugins:[{name:'fixture',setup(b){
 b.onResolve({filter:/^react(?:\/jsx-runtime)?$/},a=>({path:a.path,namespace:'react'}));
 b.onLoad({filter:/.*/,namespace:'react'},a=>({contents:a.path==='react'?'export const useState=v=>globalThis.loginHooks.state(v);':'export const jsx=(type,props)=>({type,props}),jsxs=jsx,Fragment="Fragment";'}));
 b.onResolve({filter:/auth\/betaAuthService$/},()=>({path:'auth',namespace:'auth'}));
 b.onLoad({filter:/.*/,namespace:'auth'},()=>({contents:'export const authMode=()=>"supabase",isDevAdminHandle=()=>false,requestEmailCode=e=>globalThis.loginSend(e),verifyEmailCode=(e,c)=>globalThis.loginVerify(e,c),signInAsDevAdmin=async()=>{},signInWithGoogle=async()=>null,signInWithPassword=async()=>{};'}));
}}]});
const {default:Login}=await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const nodes=x=>Array.isArray(x)?x.flatMap(nodes):x?.props?[x,...nodes(x.props.children)]:[];
const text=x=>Array.isArray(x)?x.map(text).join(''):x?.props?text(x.props.children):x??'';
const render=()=>{cursor=0;return Login({onAuthenticated(){}});};
let tree=render();
assert.equal(nodes(tree).some(n=>n.props['aria-label']==='Sign-in code'),false);
nodes(tree).find(n=>n.props.id==='login-email').props.onChange({target:{value:'artist@example.com'}});tree=render();
nodes(tree).find(n=>n.type==='form').props.onSubmit({preventDefault(){}});
await new Promise(resolve=>setImmediate(resolve));tree=render();
assert.deepEqual(sent,['artist@example.com']);assert.match(text(tree),/Check your email/);
assert.equal(nodes(tree).some(n=>n.props.id==='login-email'),false);
nodes(tree).find(n=>n.props.id==='login-code').props.onChange({target:{value:'123456'}});tree=render();
nodes(tree).find(n=>n.type==='form').props.onSubmit({preventDefault(){}});
await new Promise(resolve=>setImmediate(resolve));tree=render();assert.deepEqual(verified,[['artist@example.com','123456']]);
nodes(tree).find(n=>n.type==='button'&&text(n)==='Use another email').props.onClick();tree=render();
assert.ok(nodes(tree).find(n=>n.props.id==='login-email'));
assert.equal(nodes(tree).some(n=>n.props.id==='login-code'),false);
console.log('Login flow passed: progressive verification, fixed recipient, code submission, change-email reset.');
