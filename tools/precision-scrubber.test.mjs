import assert from 'node:assert/strict';
import { build } from 'esbuild';
const {outputFiles}=await build({entryPoints:['src/model/PrecisionScrubber.tsx'],bundle:true,write:false,format:'esm',platform:'node',jsx:'automatic',plugins:[{name:'hooks',setup(b){
 b.onResolve({filter:/^react(?:\/jsx-runtime)?$/},a=>({path:a.path,namespace:'mock'}));
 b.onLoad({filter:/.*/,namespace:'mock'},a=>({contents:a.path==='react'?'export const useId=()=>"hint",useRef=v=>({current:v}),useState=v=>[v,()=>{}];':'export const jsx=(type,props)=>({type,props});export const jsxs=jsx;'}));
}}]});
const {default:Control}=await import(`data:text/javascript;base64,${Buffer.from(outputFiles[0].text).toString('base64')}`);
const changes=[];
const tree=Control({label:'Size',value:100,min:10,max:300,unit:'%',onChange:v=>changes.push(v)});
const row=tree.props.children[0];const slider=row.props.children[2].props;
const target={focus(){},setPointerCapture(){},releasePointerCapture(){}};
const event=(extras={})=>({button:0,pointerId:1,clientX:0,shiftKey:false,currentTarget:target,preventDefault(){},stopPropagation(){},...extras});
slider.onPointerDown(event());slider.onPointerMove(event({clientX:40}));assert.equal(changes.at(-1),110);
slider.onPointerMove(event({clientX:80,shiftKey:true}));assert.equal(changes.at(-1),111,'Shift slows incremental motion without a jump');
slider.onPointerMove(event({clientX:10000}));assert.equal(changes.at(-1),300);
slider.onPointerMove(event({clientX:9996}));assert.equal(changes.at(-1),299,'Reverse immediately at the upper bound');
slider.onKeyDown(event({key:'Escape'}));assert.equal(changes.at(-1),100);
slider.onPointerMove(event({clientX:500}));assert.equal(changes.at(-1),100,'Released drag cannot change value');
slider.onPointerDown(event());slider.onPointerMove(event({clientX:8}));slider.onPointerCancel(event());assert.equal(changes.at(-1),100);
slider.onKeyDown(event({key:'ArrowRight',shiftKey:true}));assert.equal(changes.at(-1),100.1);
slider.onKeyDown(event({key:'Home'}));assert.equal(changes.at(-1),10);
slider.onKeyDown(event({key:'End'}));assert.equal(changes.at(-1),300);
slider.onKeyDown(event({key:'Home'}));
for(let i=0;i<90;i++) slider.onKeyDown(event({key:'ArrowRight'}));
assert.equal(changes.at(-1),100,'Rapid events retain each nudge before rerender');
row.props.children[1].props.onClick(event({shiftKey:true}));assert.equal(changes.at(-1),99.9);
row.props.children[3].props.onClick(event({shiftKey:true}));
slider.onPointerDown(event());slider.onPointerMove(event({clientX:1}));slider.onPointerUp(event());assert.equal(changes.at(-1),100.3);
console.log('Precision controls passed: relative drag, fine mode, bounds/reversal, cancellation, keyboard and nudge buttons.');
